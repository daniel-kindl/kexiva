using System;
using System.Diagnostics;
using System.IO;
using Xunit;

namespace Kexiva.Tests;

/// <summary>
/// Checks build properties that the BenchmarkDotNet generated project inherits.
/// </summary>
public sealed class BenchmarkProjectPropertiesTests
{
    /// <summary>
    /// Verifies that generated benchmark code does not inherit documentation-file generation.
    /// </summary>
    [Fact]
    public void AutogeneratedBenchmarkProject_DoesNotGenerateDocumentationFile()
    {
        string root = FindRepositoryRoot();
        string directory = Path.Combine(root, "TestResults", "benchmark-props-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            string generated = Path.Combine(directory, "BenchmarkDotNet.Autogenerated.csproj");
            string library = Path.Combine(directory, "Library.csproj");
            File.WriteAllText(generated, "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>");
            File.WriteAllText(library, "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>");

            Assert.Equal("false", Evaluate(generated, "GenerateDocumentationFile"), StringComparer.OrdinalIgnoreCase);
            Assert.Equal("true", Evaluate(library, "GenerateDocumentationFile"), StringComparer.OrdinalIgnoreCase);
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

    private static string Evaluate(string projectPath, string propertyName)
    {
        using Process process = new();
        process.StartInfo = new ProcessStartInfo
        {
            FileName = "dotnet",
            WorkingDirectory = Path.GetDirectoryName(projectPath)!,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        };
        process.StartInfo.ArgumentList.Add("msbuild");
        process.StartInfo.ArgumentList.Add(projectPath);
        process.StartInfo.ArgumentList.Add("-nologo");
        process.StartInfo.ArgumentList.Add("-getProperty:" + propertyName);
        process.Start();
        string output = process.StandardOutput.ReadToEnd();
        string error = process.StandardError.ReadToEnd();
        process.WaitForExit();
        Assert.True(process.ExitCode == 0, error);
        return output.Trim();
    }

    private static string FindRepositoryRoot()
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Kexiva.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName ?? throw new DirectoryNotFoundException("Could not find Kexiva.slnx.");
    }
}
